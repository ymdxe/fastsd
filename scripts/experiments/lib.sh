#!/usr/bin/env bash
# Shared helpers for experiment operations.  This file intentionally contains
# no deletion, process discovery/termination, or credential handling logic.

if [[ -n "${FASTSD_EXPERIMENTS_LIB_LOADED:-}" ]]; then
  return 0
fi
readonly FASTSD_EXPERIMENTS_LIB_LOADED=1

EXPERIMENTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
REPO_ROOT="$(cd "${EXPERIMENTS_DIR}/../.." && pwd -P)"

die() {
  echo "ERROR: $*" >&2
  exit 2
}

note() {
  echo "[fastsd-experiment] $*" >&2
}

need_command() {
  command -v "$1" >/dev/null 2>&1 || die "Required command is unavailable: $1"
}

require_repo_root() {
  [[ -d "${REPO_ROOT}/.git" || -f "${REPO_ROOT}/.git" ]] || die "Repository root is not a Git worktree: ${REPO_ROOT}"
}

require_file() {
  [[ -f "$1" ]] || die "Required file does not exist: $1"
}

require_executable_or_command() {
  local value="$1"
  if [[ "${value}" == */* ]]; then
    [[ -x "${value}" ]] || die "Required executable does not exist or is not executable: ${value}"
  else
    need_command "${value}"
  fi
}

require_directory() {
  [[ -d "$1" ]] || die "Required directory does not exist: $1"
}

validate_run_id() {
  [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$ ]] || die "Invalid run id '$1'; use letters, numbers, dot, underscore, or dash."
}

validate_ipv4() {
  local value="$1"
  local IFS=.
  local -a octets
  read -r -a octets <<< "${value}"
  [[ ${#octets[@]} -eq 4 ]] || die "Invalid IPv4 address: ${value}"
  local octet
  for octet in "${octets[@]}"; do
    [[ "${octet}" =~ ^[0-9]{1,3}$ ]] || die "Invalid IPv4 address: ${value}"
    ((10#${octet} <= 255)) || die "Invalid IPv4 address: ${value}"
  done
}

validate_port() {
  [[ "$1" =~ ^[0-9]+$ ]] || die "Invalid port: $1"
  ((10#$1 >= 1 && 10#$1 <= 65535)) || die "Port out of range: $1"
}

validate_host_alias() {
  [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || die "Invalid SSH host alias: $1"
}

validate_hdd_path() {
  local path="$1"
  [[ -n "${path}" ]] || die "Path must not be empty."
  [[ "${path}" != *$'\n'* && "${path}" != *$'\r'* ]] || die "Path contains a newline."
  [[ "${path}" =~ ^/home/hdd(/[-A-Za-z0-9._+=,@%]+)*$ ]] || die "Experiment paths must be explicitly under /home/hdd and use safe path characters: ${path}"
  [[ "/${path}/" != *"/../"* ]] || die "Path traversal is not allowed: ${path}"
}

assert_fresh_path() {
  local path="$1"
  [[ ! -e "${path}" && ! -L "${path}" ]] || die "Refusing to reuse existing path: ${path}"
}

assert_fresh_component_run_path() {
  local component_path="$1"
  local expected_component="$2"
  [[ "$(basename "${component_path}")" == "${expected_component}" ]] || die "Run component path must end in /${expected_component}: ${component_path}"
  assert_fresh_path "${component_path}"
  # A component is always created on one host before any sibling exists there.
  # Requiring a new run-id parent prevents a stale partial run from being mixed
  # with new artifacts.  The collection wrapper is the only operation allowed
  # to work with an existing root that already contains edge/.
  assert_fresh_path "$(dirname "${component_path}")"
}

nearest_existing_directory() {
  local path="$1"
  while [[ ! -d "${path}" ]]; do
    local parent
    parent="$(dirname "${path}")"
    [[ "${parent}" != "${path}" ]] || die "No existing parent directory for path: $1"
    path="${parent}"
  done
  printf '%s\n' "${path}"
}

available_gib() {
  local path="$1"
  local existing
  existing="$(nearest_existing_directory "${path}")"
  df -Pk "${existing}" | awk 'NR==2 { printf "%.3f", $4 / 1024 / 1024 }'
}

validate_gpu_list() {
  local value="$1"
  local expected_count="$2"
  [[ "${value}" =~ ^[0-9]+(,[0-9]+)*$ ]] || die "GPU list must be comma-separated non-negative indexes: ${value}"
  local IFS=,
  local -a gpu_ids
  read -r -a gpu_ids <<< "${value}"
  [[ ${#gpu_ids[@]} -eq ${expected_count} ]] || die "Expected ${expected_count} GPU index(es), got '${value}'."
  local -A seen=()
  local gpu
  for gpu in "${gpu_ids[@]}"; do
    [[ -z "${seen[${gpu}]:-}" ]] || die "GPU index appears more than once: ${gpu}"
    seen[${gpu}]=1
  done
}

write_command_file() {
  local destination="$1"
  shift
  [[ ! -e "${destination}" && ! -L "${destination}" ]] || die "Refusing to overwrite command record: ${destination}"
  {
    printf '# Generated by FastSD experiment wrapper at %s\n' "$(date --iso-8601=seconds)"
    printf 'exec '
    printf '%q ' "$@"
    printf '\n'
  } > "${destination}"
}

metadata_python() {
  local python_bin="${FASTSD_METADATA_PYTHON:-${FASTSD_PYTHON:-python3}}"
  local tool="${EXPERIMENTS_DIR}/capture_run_metadata.py"
  require_file "${tool}"
  "${python_bin}" "${tool}" "$@"
}

sampler_python() {
  local python_bin="${FASTSD_METADATA_PYTHON:-${FASTSD_PYTHON:-python3}}"
  local tool="${EXPERIMENTS_DIR}/gpu_sampler.py"
  require_file "${tool}"
  # Wrappers background this function and later signal $!.  Replace the
  # function subshell with Python so $! is the actual sampler PID; otherwise
  # terminating the shell leaves an orphan sampler and reports exit 143.
  exec "${python_bin}" "${tool}" "$@"
}

safe_sha256() {
  local path="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "${path}" | awk '{print $1}'
  else
    python3 - "${path}" <<'PY'
import hashlib
import pathlib
import sys
path = pathlib.Path(sys.argv[1])
h = hashlib.sha256()
with path.open("rb") as handle:
    for block in iter(lambda: handle.read(1024 * 1024), b""):
        h.update(block)
print(h.hexdigest())
PY
  fi
}
